//! G-code programs:
//! * 3D printing: the slicer and its settings (layer height, filament type
//!   and use, printer model, nozzle), estimated print time, layers,
//!   temperatures, thumbnails, commands and the extent of the moves;
//! * CNC (ISO 6983 / RS-274): program number and comments, units, tools,
//!   spindle speeds, feed rates, commands and the extent of the moves.
//!
//! Specifications: NIST RS-274NGC v3; the slicers' comment conventions
//! (`PrusaSlicer` / `SuperSlicer` / `OrcaSlicer` `; key = value`, Cura `;KEY:`,
//! `Simplify3D`); Marlin and `RepRap` G-code references.

use std::collections::BTreeMap;

use serde_json::{Map, Value};

use super::{Box3, bump, hist, num};
use crate::plugin::{
    Context, Cost, ExtractError, Extractor, ExtractorMeta, FormatSpec, Probe, Sniff, Source, truncate_chars,
};

/// Extractor for G-code.
pub struct Gcode;

static META: ExtractorMeta = ExtractorMeta {
    id: "cad.gcode",
    version: 1,
    cost: Cost::Scan,
    priority: 0,
    formats: &[
        FormatSpec {
            id: "gcode",
            name: "3D printing G-code",
            family: "3d",
            mimes: &["text/x-gcode"],
            extensions: &["gcode", "gco"],
            magic: &[],
            parent: Some("text"),
        },
        // `.nc` is also NetCDF: CNC programs are sniffed.
        FormatSpec {
            id: "cnc_gcode",
            name: "CNC / ISO G-code",
            family: "cad",
            mimes: &[],
            extensions: &["ngc", "tap", "cnc"],
            magic: &[],
            parent: Some("text"),
        },
    ],
};

/// Slicer settings worth reporting, PrusaSlicer-style keys.
const SETTINGS: [&str; 16] = [
    "layer_height",
    "first_layer_height",
    "filament_type",
    "filament_settings_id",
    "printer_model",
    "printer_settings_id",
    "print_settings_id",
    "nozzle_diameter",
    "fill_density",
    "perimeters",
    "support_material",
    "estimated printing time (normal mode)",
    "filament used [mm]",
    "filament used [g]",
    "total filament used [g]",
    "total layers count",
];

/// A word's number: `X12.5` → 12.5.
fn word(line: &str, letter: char) -> Option<f64> {
    line.split_whitespace().find_map(|w| w.strip_prefix(letter).and_then(|v| v.parse::<f64>().ok()))
}

#[allow(clippy::too_many_lines)] // one arm per command family
fn gcode(cx: &mut Context<'_>, text: &str, cnc: bool) {
    let mut commands: BTreeMap<String, u64> = BTreeMap::new();
    let mut settings = Map::new();
    let (mut layers, mut thumbnails, mut tools) = (0u64, Vec::new(), std::collections::BTreeSet::new());
    let mut temps: BTreeMap<&str, f64> = BTreeMap::new();
    let mut comments = Vec::new();
    let mut slicer = None;
    let mut b = Box3::default();
    let (mut x, mut y, mut z) = (0.0f64, 0.0f64, 0.0f64);
    let mut absolute = true;
    let mut units = None;
    let (mut spindle, mut feed) = (Vec::new(), (f64::INFINITY, 0.0f64));
    let mut program = None;
    for line in text.lines().take(100_000_000) {
        let t = line.trim();
        // Comments: `; …` (printers) and `( … )` (CNC).
        let (code, comment) = match t.find(';') {
            Some(i) => (t[..i].trim(), Some(t[i + 1..].trim())),
            None => (t, None),
        };
        if let Some(c) = comment {
            let lower = c.to_ascii_lowercase();
            if slicer.is_none() && (lower.starts_with("generated by") || lower.starts_with("generated with")) {
                slicer = Some(truncate_chars(c, 200));
            } else if c.starts_with("LAYER:")
                || c == "LAYER_CHANGE"
                || lower.starts_with("layer ")
                    && lower.split_whitespace().nth(1).is_some_and(|n| n.parse::<u64>().is_ok())
            {
                layers += 1;
            } else if let Some(r) = c.strip_prefix("thumbnail begin") {
                if thumbnails.len() < 10 {
                    thumbnails.push(truncate_chars(r.split_whitespace().next().unwrap_or(""), 20));
                }
            } else if let Some((k, v)) = c.split_once(" = ") {
                if SETTINGS.contains(&k.trim()) && settings.len() < 40 {
                    settings.insert(
                        k.trim().replace(' ', "_").replace(['[', ']', '(', ')'], ""),
                        truncate_chars(v.trim(), 100).into(),
                    );
                }
            } else if let Some((k, v)) = c.split_once(':') {
                // Cura: ;FLAVOR:Marlin ;TIME:1234 ;Filament used: 1.2m ;Layer height: 0.2
                match k {
                    "FLAVOR"
                    | "TIME"
                    | "Filament used"
                    | "Layer height"
                    | "LAYER_COUNT"
                    | "TARGET_MACHINE.NAME"
                    | "MINX"
                    | "MAXX"
                    | "MINY"
                    | "MAXY"
                    | "MINZ"
                    | "MAXZ" => {
                        settings.insert(
                            k.to_ascii_lowercase().replace([' ', '.'], "_"),
                            truncate_chars(v.trim(), 100).into(),
                        );
                    }
                    _ => {}
                }
            }
        }
        if code.is_empty() {
            continue;
        }
        if cnc {
            if code == "%" {
                continue;
            }
            if let Some(p) = code.strip_prefix('O').filter(|p| p.chars().next().is_some_and(|c| c.is_ascii_digit())) {
                program.get_or_insert_with(|| truncate_chars(p.split_whitespace().next().unwrap_or(""), 20));
            }
            for (i, _) in code.match_indices('(').take(5) {
                if let Some(c) = code[i + 1..].split(')').next()
                    && comments.len() < 30
                {
                    comments.push(truncate_chars(c.trim(), 200));
                }
            }
        }
        // Words without the parenthesised comments.
        let clean: String = {
            let mut out = String::new();
            let mut depth = 0;
            for ch in code.chars() {
                match ch {
                    '(' => depth += 1,
                    ')' => depth = (depth - 1).max(0),
                    _ if depth == 0 => out.push(ch.to_ascii_uppercase()),
                    _ => {}
                }
            }
            out
        };
        let mut words = clean.split_whitespace().peekable();
        // Line numbers (N…) come first.
        if words.peek().is_some_and(|w| w.starts_with('N')) {
            words.next();
        }
        let Some(cmd) = words.next() else { continue };
        let key = match cmd.as_bytes().first() {
            Some(b'G' | b'M') => {
                let n: f64 = cmd[1..].parse().unwrap_or(-1.0);
                format!("{}{}", &cmd[..1], if n.fract() == 0.0 { format!("{n:.0}") } else { format!("{n}") })
            }
            Some(b'T') => {
                tools.insert(truncate_chars(cmd, 10));
                "T".to_string()
            }
            Some(b'X' | b'Y' | b'Z') => "G1 (modal)".to_string(),
            _ => continue,
        };
        bump(&mut commands, &key, 200);
        match key.as_str() {
            "G90" => absolute = true,
            "G91" => absolute = false,
            "G20" => units = Some("inch"),
            "G21" => units = Some("mm"),
            "M104" | "M109" => {
                if let Some(s) = word(&clean, 'S') {
                    temps.insert("hotend", temps.get("hotend").copied().unwrap_or(0.0).max(s));
                }
            }
            "M140" | "M190" => {
                if let Some(s) = word(&clean, 'S') {
                    temps.insert("bed", temps.get("bed").copied().unwrap_or(0.0).max(s));
                }
            }
            "M3" | "M4" => {
                if let Some(s) = word(&clean, 'S')
                    && spindle.len() < 50
                {
                    spindle.push(s);
                }
            }
            _ => {}
        }
        if matches!(key.as_str(), "G0" | "G1" | "G2" | "G3" | "G1 (modal)") {
            if let Some(f) = word(&clean, 'F') {
                feed = (feed.0.min(f), feed.1.max(f));
            }
            let (nx, ny, nz) = (word(&clean, 'X'), word(&clean, 'Y'), word(&clean, 'Z'));
            if nx.is_none() && ny.is_none() && nz.is_none() {
                continue;
            }
            if absolute {
                x = nx.unwrap_or(x);
                y = ny.unwrap_or(y);
                z = nz.unwrap_or(z);
            } else {
                x += nx.unwrap_or(0.0);
                y += ny.unwrap_or(0.0);
                z += nz.unwrap_or(0.0);
            }
            b.add([x, y, z]);
        }
    }
    if let Some(s) = slicer {
        cx.format_set("generator", s);
    }
    if let Some(p) = program {
        cx.format_set("program", p);
    }
    if !comments.is_empty() {
        cx.format_set("comments", comments);
    }
    if let Some(u) = units {
        cx.format_set("units", u);
    }
    if !settings.is_empty() {
        cx.format_set("settings", Value::Object(settings));
    }
    if !cnc {
        cx.format_set("layers", layers);
        if !thumbnails.is_empty() {
            cx.format_set("thumbnails", thumbnails);
        }
        let mut t = Map::new();
        for (k, v) in temps {
            t.insert(k.into(), num(v, 1));
        }
        if !t.is_empty() {
            cx.format_set("max_temperatures_c", Value::Object(t));
        }
    }
    if !tools.is_empty() {
        cx.format_set("tools", tools.into_iter().collect::<Vec<_>>());
    }
    if !spindle.is_empty() {
        cx.format_set("spindle_speeds", spindle.iter().map(|&s| num(s, 0)).collect::<Vec<_>>());
    }
    if feed.1 > 0.0 {
        cx.format_set("feed_range", Value::Array(vec![num(feed.0, 1), num(feed.1, 1)]));
    }
    cx.format_set("commands", hist(commands));
    b.report(cx, "move_extent");
}

impl Extractor for Gcode {
    fn meta(&self) -> &'static ExtractorMeta {
        &META
    }

    fn sniff(&self, probe: &Probe<'_>) -> Option<Sniff> {
        let h = probe.head;
        let text = std::str::from_utf8(&h[..h.len().min(16 << 10)]).ok()?;
        let lines: Vec<&str> = text.lines().take(400).map(str::trim).collect();
        let moves = lines
            .iter()
            .filter(|l| l.starts_with("G0 ") || l.starts_with("G1 ") || l.starts_with("G00") || l.starts_with("G01"))
            .count();
        let slicer = text.contains("; generated by")
            || text.contains(";Generated with")
            || text.contains(";FLAVOR:")
            || text.contains("; generated with");
        if slicer || moves >= 3 && text.contains(" E") && matches!(probe.extension, Some("gcode" | "gco" | "g")) {
            return Some(Sniff { format: "gcode", confidence: 0.97 });
        }
        let cnc_ext = matches!(probe.extension, Some("nc" | "ngc" | "tap" | "cnc" | "gcode"));
        let program = lines.first().is_some_and(|l| *l == "%")
            || lines.iter().take(5).any(|l| l.starts_with('O') && l[1..].starts_with(|c: char| c.is_ascii_digit()));
        let cnc = (program || cnc_ext)
            && moves
                + lines
                    .iter()
                    .filter(|l| {
                        l.starts_with("G90") || l.starts_with("G21") || l.starts_with("M3") || l.starts_with("M6")
                    })
                    .count()
                >= 2;
        cnc.then_some(Sniff { format: "cnc_gcode", confidence: 0.95 })
    }

    fn extract(&self, src: &mut dyn Source, cx: &mut Context<'_>) -> Result<(), ExtractError> {
        let cnc = cx.format_id() == "cnc_gcode";
        let text = cx.read_text(src)?.text;
        gcode(cx, &text, cnc);
        Ok(())
    }
}

crate::register_extractor!(Gcode);

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn words() {
        assert_eq!(word("G1 X12.5 Y-3 F1800", 'X'), Some(12.5));
        assert_eq!(word("G1 X12.5 Y-3 F1800", 'Y'), Some(-3.0));
        assert_eq!(word("G1 X12.5", 'Z'), None);
    }

    crate::fixture_tests!("gcode", "cnc_gcode");
}
